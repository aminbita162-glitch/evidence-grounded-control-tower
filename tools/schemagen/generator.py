"""Schema-to-Pydantic model generator (Part 3 §3.3, P03-T01).

Reads JSON Schema files from ``schemas/`` and emits frozen, strictly typed
Pydantic v2 model source files into ``kernel/contracts/_generated/``.

Properties:
- Reproducible: the same schema files always produce byte-identical output.
- Every generated file carries the header ``# AUTO-GENERATED — DO NOT EDIT``.
- Models are frozen (``frozen=True``) and strict (``strict=True``).
- No untyped dictionary crosses a module boundary.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path
from typing import Any

_GENERATED_HEADER = "# AUTO-GENERATED — DO NOT EDIT — regenerated by tools/schemagen\n"

# Map $ref common.json definitions to Python type annotations.
_REF_MAP: dict[str, str] = {
    "common.json#/definitions/tenant_id": "str",
    "common.json#/definitions/schema_version": "int",
    "common.json#/definitions/timestamp": "str",
    "common.json#/definitions/hash_hex": "str",
    "common.json#/definitions/id_field": "str",
}


def _resolve_ref(ref: str) -> str:
    """Resolve a ``$ref`` to a Python type annotation string."""
    if ref in _REF_MAP:
        return _REF_MAP[ref]
    return "str"


def _json_type_to_python(prop: dict[str, Any]) -> str:
    """Map a JSON Schema property to a Python type annotation string."""
    if "$ref" in prop:
        return _resolve_ref(prop["$ref"])
    json_type = prop.get("type")
    if isinstance(json_type, list):
        if "null" in json_type and "string" in json_type:
            return "str | None"
        non_null = [t for t in json_type if t != "null"]
        if len(non_null) == 1:
            base = _scalar_type(non_null[0])
            return f"{base} | None"
    if json_type == "array":
        items = prop.get("items", {})
        item_type = _json_type_to_python(items)
        return f"list[{item_type}]"
    if json_type == "object":
        return "dict[str, str]"
    if "enum" in prop and json_type == "string":
        values = ", ".join(f'"{v}"' for v in prop["enum"])
        return f"Literal[{values}]"
    return _scalar_type(json_type or "string")


def _scalar_type(json_type: str) -> str:
    """Map a scalar JSON Schema type to a Python type annotation."""
    mapping = {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
    }
    return mapping.get(json_type, "str")


def _generate_model_source(
    class_name: str,
    schema: dict[str, Any],
) -> str:
    """Generate Python source for a single Pydantic model from a JSON Schema."""
    properties: dict[str, Any] = schema.get("properties", {})
    required: list[str] = schema.get("required", [])
    description = schema.get("description", "")

    lines: list[str] = [_GENERATED_HEADER]
    lines.append('"""')
    lines.append(f"{class_name} — {description}")
    lines.append("")
    lines.append("Auto-generated from the JSON Schema; do not edit by hand.")
    lines.append('"""')
    lines.append("")
    lines.append("from __future__ import annotations")
    lines.append("")

    # Only import Literal when the schema uses enum fields.
    uses_literal = any("enum" in prop for prop in properties.values() if isinstance(prop, dict))
    if uses_literal:
        lines.append("from typing import Literal")
        lines.append("")

    lines.append("from pydantic import BaseModel, ConfigDict")
    lines.append("")
    lines.append("")
    lines.append(f"class {class_name}(BaseModel):")
    lines.append(f'    """{class_name} model (frozen, strict)."""')
    lines.append("    model_config = ConfigDict(frozen=True, strict=True)")
    lines.append("")

    # Sort: required fields first (alphabetical), then optional (alphabetical).
    required_props = sorted((k, v) for k, v in properties.items() if k in required)
    optional_props = sorted((k, v) for k, v in properties.items() if k not in required)

    for name, prop in required_props:
        py_type = _json_type_to_python(prop)
        lines.append(f"    {name}: {py_type}")

    for name, prop in optional_props:
        py_type = _json_type_to_python(prop)
        if not py_type.endswith("| None"):
            py_type = f"{py_type} | None"
        lines.append(f"    {name}: {py_type} = None")

    if not properties:
        lines.append("    pass")

    lines.append("")
    return "\n".join(lines)


def _class_name_from_schema(schema: dict[str, Any], fallback: str) -> str:
    """Derive a PascalCase class name from the schema title or fallback."""
    title = schema.get("title", fallback)
    return str(title).replace(" ", "").replace("_", "")


def _snake_to_pascal(name: str) -> str:
    """Convert a snake_case filename to PascalCase."""
    return "".join(part.capitalize() for part in name.split("_"))


def generate_all(schemas_dir: Path, output_dir: Path) -> list[Path]:
    """Generate all model files from JSON Schema files in *schemas_dir*.

    Args:
        schemas_dir: Directory containing entity JSON Schema files.
        output_dir: Directory to write generated model files to.

    Returns:
        List of paths to generated files.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    generated: list[Path] = []

    # Skip non-entity schemas (common.json, labels.json, etc.)
    _skip = {
        "common.json",
        "labels.json",
        "license-manifest.json",
        "gap.json",
        "hash-tags.json",
    }
    entity_files = sorted(f for f in schemas_dir.glob("*.json") if f.name not in _skip)

    # Track which .py stems we generate so we can clean up stale files.
    expected_stems: set[str] = set()

    for schema_file in entity_files:
        schema = json.loads(schema_file.read_text(encoding="utf-8"))
        class_name = _class_name_from_schema(schema, _snake_to_pascal(schema_file.stem))
        source = _generate_model_source(class_name, schema)
        out_path = output_dir / f"{schema_file.stem}.py"
        out_path.write_text(source, encoding="utf-8")
        generated.append(out_path)
        expected_stems.add(schema_file.stem)

    # Remove stale generated .py files (no longer corresponding to any schema).
    for existing in output_dir.glob("*.py"):
        if existing.stem != "__init__" and existing.stem not in expected_stems:
            existing.unlink()

    # Generate __init__.py that re-exports all models.
    init_lines: list[str] = [
        _GENERATED_HEADER,
        '"""Generated models package — re-exports all entity models."""',
        "",
        "from __future__ import annotations",
        "",
    ]
    for f in entity_files:
        schema = json.loads(f.read_text(encoding="utf-8"))
        class_name = _class_name_from_schema(schema, _snake_to_pascal(f.stem))
        init_lines.append(f"from kernel.contracts._generated.{f.stem} import {class_name}")
    init_lines.append("")
    init_lines.append("__all__ = [")
    for f in entity_files:
        schema = json.loads(f.read_text(encoding="utf-8"))
        class_name = _class_name_from_schema(schema, _snake_to_pascal(f.stem))
        init_lines.append(f'    "{class_name}",')
    init_lines.append("]")
    init_lines.append("")
    init_path = output_dir / "__init__.py"
    init_path.write_text("\n".join(init_lines), encoding="utf-8")
    generated.append(init_path)

    # Format generated files with ruff for byte-identical, consistent output.
    ruff_bin = Path(sys.executable).parent / "ruff"
    if ruff_bin.exists():
        subprocess.run(  # noqa: S603
            [str(ruff_bin), "format", str(output_dir)],
            check=True,
            capture_output=True,
        )

    return generated


def _repo_root() -> Path:
    """Resolve the repository root."""
    return Path(__file__).resolve().parents[2]


def regenerate() -> int:
    """Regenerate all model files and report the count.

    Returns:
        Exit code: 0 on success, 1 on error.
    """
    root = _repo_root()
    schemas_dir = root / "schemas"
    output_dir = root / "kernel" / "contracts" / "_generated"
    files = generate_all(schemas_dir, output_dir)
    print(f"generated: {len(files)} files in {output_dir.relative_to(root)}")
    return 0
