"""SQL table definition generator (P04-T02).

Reads JSON Schema files from ``schemas/`` and generates SQL ``CREATE TABLE``
statements for every persisted entity.  Each table carries:

- ``id`` — ``TEXT PRIMARY KEY``, the opaque time-sortable identifier assigned
  by the Kernel (never a database sequence).
- ``tenant_id`` — ``TEXT NOT NULL``, the tenant scope.
- ``schema_version`` — ``INTEGER NOT NULL``, the schema version for migration
  tracking.
- Entity-specific columns mapped from the JSON Schema properties.

Foreign keys are tenant-scoped (composite: ``(tenant_id, ref_id)``) so a
row from one tenant cannot reference a row from another.  FK constraints
are added via ``ALTER TABLE`` after all tables exist, so forward references
work regardless of alphabetical order.

The output is deterministic and byte-identical on every run.

Spec: Part 3 §3.3; Part 4 §4.4; P04-T02.
"""

from __future__ import annotations

import json
from pathlib import Path

__all__ = [
    "generate_sql_tables",
    "generate_support_library_migration",
    "generate_passport_configuration_migration",
    "regenerate_sql",
]

_SKIP: set[str] = {
    "common.json",
    "labels.json",
    "license-manifest.json",
    "gap.json",
    "hash-tags.json",
    "case-states.json",
    "config.json",
    "errors.json",
    "model_call.json",
    "region_profile.json",
}

_PASSPORT_CONFIGURATION_COLUMN = "configuration_hash"
_PASSPORT_CONFIGURATION_MIGRATION = "0008_passport_configuration_hash.sql"

_DECISION_TRACE_COLUMN = "calculation_trace_hashes"
_PASSPORT_OPEN_ITEMS_COLUMN = "open_items"
_SUPPORT_LIBRARY_MIGRATION = "0009_support_library_references.sql"
_FORWARD_COLUMNS = {
    ("passport", _PASSPORT_CONFIGURATION_COLUMN),
    ("passport", _PASSPORT_OPEN_ITEMS_COLUMN),
    ("decision", _DECISION_TRACE_COLUMN),
}

_HEADER = (
    "-- 0002_tables.sql — entity tables generated from schemas (P04-T02)\n"
    "--\n"
    "-- Expand-then-contract convention: every table is created here and\n"
    "-- only removed by a later contract migration.  Each table carries\n"
    "-- tenant_id, schema_version and a time-sortable primary key (id).\n"
    "-- No SERIAL columns or shared sequences: identifiers are assigned\n"
    "-- by the Kernel, not the database.\n"
    "--\n"
    "-- Generated by tools/schemagen/sqlgen.py — do not edit by hand.\n"
)

_REF_MAP: dict[str, str] = {
    "common.json#/definitions/tenant_id": "TEXT",
    "common.json#/definitions/schema_version": "INTEGER",
    "common.json#/definitions/timestamp": "TIMESTAMPTZ",
    "common.json#/definitions/hash_hex": "TEXT",
    "common.json#/definitions/id_field": "TEXT",
}


def _resolve_ref(ref: str) -> str:
    return _REF_MAP.get(ref, "TEXT")


def _json_type_to_sql(prop: dict[str, object]) -> str:
    if "$ref" in prop:
        return _resolve_ref(str(prop["$ref"]))
    json_type = prop.get("type")
    if json_type == "array":
        return "JSONB"
    if json_type == "object":
        return "JSONB"
    if json_type == "integer":
        return "INTEGER"
    if json_type == "number":
        return "NUMERIC"
    if json_type == "boolean":
        return "BOOLEAN"
    return "TEXT"


def _table_name(stem: str) -> str:
    return f'"{stem}"'


def _entity_id_field(stem: str, properties: dict[str, object]) -> str | None:
    expected = f"{stem}_id"
    if expected in properties:
        return expected
    return None


def _is_fk_id(name: str, all_stems: set[str]) -> str | None:
    if name.endswith("_id"):
        ref_stem = name[:-3]
        if ref_stem in all_stems:
            return ref_stem
    return None


def generate_sql_tables(schemas_dir: Path) -> str:
    """Generate SQL CREATE TABLE and ALTER TABLE statements from entity schemas.

    Tables are created first without foreign keys, then FK constraints are
    added via ``ALTER TABLE`` so that forward references work regardless of
    alphabetical order.

    Args:
        schemas_dir: directory containing entity JSON Schema files.

    Returns:
        SQL string with CREATE TABLE and ALTER TABLE statements.
    """
    entity_files = sorted(f for f in schemas_dir.glob("*.json") if f.name not in _SKIP)
    all_stems = {f.stem for f in entity_files}
    lines: list[str] = [_HEADER, ""]
    fk_alterations: list[str] = []

    for schema_file in entity_files:
        schema = json.loads(schema_file.read_text(encoding="utf-8"))
        properties = schema.get("properties", {})
        if not isinstance(properties, dict):
            continue
        table = _table_name(schema_file.stem)
        id_field = _entity_id_field(schema_file.stem, properties)

        col_lines: list[str] = []
        col_lines.append("    id TEXT PRIMARY KEY")
        col_lines.append("    tenant_id TEXT NOT NULL")
        col_lines.append("    schema_version INTEGER NOT NULL")
        col_lines.append("    UNIQUE (tenant_id, id)")

        for name, prop in sorted(properties.items()):
            if name in ("tenant_id", "schema_version"):
                continue
            if id_field and name == id_field:
                continue
            # Columns introduced after 0002 belong to their forward migrations.
            if (schema_file.stem, name) in _FORWARD_COLUMNS:
                continue
            sql_type = _json_type_to_sql(prop)
            if prop.get("type") == "string" and "enum" in prop:
                values = prop.get("enum", [])
                if isinstance(values, list) and values:
                    quoted = ", ".join(f"'{v}'" for v in values)
                    col_lines.append(f"    {name} {sql_type} CHECK ({name} IN ({quoted}))")
                else:
                    col_lines.append(f"    {name} {sql_type}")
            else:
                required = schema.get("required", [])
                nullable = "" if name in required else " DEFAULT NULL"
                col_lines.append(f"    {name} {sql_type}{nullable}")
            fk_ref = _is_fk_id(name, all_stems)
            if fk_ref and fk_ref != schema_file.stem:
                constraint_name = f"fk_{schema_file.stem}_{name}"
                fk_alterations.append(
                    f"ALTER TABLE {table} ADD CONSTRAINT {constraint_name} "
                    f"FOREIGN KEY (tenant_id, {name}) "
                    f'REFERENCES "{fk_ref}"(tenant_id, id)'
                )

        lines.append(f"CREATE TABLE IF NOT EXISTS {table} (")
        lines.append(",\n".join(col_lines))
        lines.append(");")
        lines.append("")

    if fk_alterations:
        lines.append("-- Foreign key constraints (added after all tables exist)")
        lines.append("")
        for alter in fk_alterations:
            lines.append(alter + ";")
        lines.append("")

    return "\n".join(lines)


def generate_passport_configuration_migration(schemas_dir: Path) -> str:
    """Generate the additive migration for the optional Passport configuration hash."""
    passport = json.loads((schemas_dir / "passport.json").read_text(encoding="utf-8"))
    column = _PASSPORT_CONFIGURATION_COLUMN
    definition = passport["properties"][column]
    if (
        column in passport["required"]
        or definition.get("$ref") != "common.json#/definitions/hash_hex"
    ):
        msg = "Passport configuration_hash must be an optional SHA-256 hash"
        raise ValueError(msg)
    sql_type = _json_type_to_sql(definition)
    return (
        "-- P12-CHG: Add the deployment configuration hash to Passport storage.\n"
        'ALTER TABLE "passport"\n'
        f"    ADD COLUMN IF NOT EXISTS {column} {sql_type} DEFAULT NULL;\n"
    )


def generate_support_library_migration(schemas_dir: Path) -> str:
    """Generate the additive migration for Phase 13 Decision and Passport fields."""
    statements = ["-- P13: Add optional calculation trace references and Passport open items."]
    for entity, column, item_type in (
        ("decision", _DECISION_TRACE_COLUMN, {"$ref": "common.json#/definitions/hash_hex"}),
        ("passport", _PASSPORT_OPEN_ITEMS_COLUMN, {"type": "object"}),
    ):
        schema = json.loads((schemas_dir / f"{entity}.json").read_text(encoding="utf-8"))
        definition = schema["properties"][column]
        if (
            column in schema["required"]
            or definition.get("type") != "array"
            or any(
                definition.get("items", {}).get(key) != value for key, value in item_type.items()
            )
        ):
            raise ValueError(f"{entity}.{column} must be an optional array with the expected items")
        sql_type = _json_type_to_sql(definition)
        statements.extend(
            (
                f'ALTER TABLE "{entity}"',
                f"    ADD COLUMN IF NOT EXISTS {column} {sql_type} DEFAULT NULL;",
            )
        )
    return "\n".join(statements) + "\n"


def regenerate_sql() -> int:
    """Verify the original table migration and regenerate the forward migration."""
    root = Path(__file__).resolve().parents[2]
    schemas_dir = root / "schemas"
    migrations_dir = root / "adapters" / "postgres" / "migrations"
    original = migrations_dir / "0002_tables.sql"
    if generate_sql_tables(schemas_dir).encode("utf-8") != original.read_bytes():
        print(f"immutable migration differs from generation: {original.relative_to(root)}")
        return 1
    migrations = {
        _PASSPORT_CONFIGURATION_MIGRATION: generate_passport_configuration_migration(schemas_dir),
        _SUPPORT_LIBRARY_MIGRATION: generate_support_library_migration(schemas_dir),
    }
    for name, sql in migrations.items():
        forward = migrations_dir / name
        forward.write_bytes(sql.encode("utf-8"))
        print(f"generated: {forward.relative_to(root)}")
    return 0
