"""Evaluator generator for the rule engine (Part 3 §3.6, P06-T04).

Generates typed evaluators from DSL definitions.  Generated files are
marked, reproducible (byte-identical on rebuild) and never edited by hand.
Production uses the reference interpreter; the generated evaluator is the
independent oracle of the differential test.
"""

from __future__ import annotations

from pathlib import Path

__all__ = ["generate_evaluator", "regenerate"]

_GENERATED_HEADER = "# AUTO-GENERATED — DO NOT EDIT — regenerated by tools.rulegen\n"

_USED_TYPES: list[str] = [
    "Add",
    "All",
    "And",
    "AnyExpr",
    "BoolLit",
    "CountExpr",
    "DateLit",
    "DecimalLit",
    "Div",
    "Eq",
    "FieldRef",
    "Ge",
    "Gt",
    "In",
    "IntLit",
    "Le",
    "Lt",
    "Mul",
    "Ne",
    "Not",
    "Or",
    "StringEq",
    "StringLit",
    "Sub",
]


def _dispatch_entries() -> list[tuple[str, list[str]]]:
    """Return (class_name, body_lines) pairs for the dispatch."""
    return [
        ("BoolLit", ["return expr.value"]),
        ("IntLit", ["return expr.value"]),
        ("DecimalLit", ["return expr.value"]),
        ("StringLit", ["return expr.value"]),
        (
            "DateLit",
            [
                "y = expr.year",
                "m = expr.month",
                "d = expr.day",
                "return f'{y:04d}-{m:02d}-{d:02d}'",
            ],
        ),
        ("FieldRef", ["return _get_fact(facts, expr.name)"]),
        ("And", ["return all(_evaluate(o, facts) for o in expr.operands)"]),
        ("Or", ["return any(_evaluate(o, facts) for o in expr.operands)"]),
        ("Not", ["return not _evaluate(expr.operand, facts)"]),
        (
            "Eq",
            [
                "l = str(_evaluate(expr.left, facts))",
                "r = str(_evaluate(expr.right, facts))",
                "return l == r",
            ],
        ),
        (
            "Ne",
            [
                "l = str(_evaluate(expr.left, facts))",
                "r = str(_evaluate(expr.right, facts))",
                "return l != r",
            ],
        ),
        (
            "Lt",
            [
                "l = _to_decimal(_evaluate(expr.left, facts))",
                "r = _to_decimal(_evaluate(expr.right, facts))",
                "return l < r",
            ],
        ),
        (
            "Le",
            [
                "l = _to_decimal(_evaluate(expr.left, facts))",
                "r = _to_decimal(_evaluate(expr.right, facts))",
                "return l <= r",
            ],
        ),
        (
            "Gt",
            [
                "l = _to_decimal(_evaluate(expr.left, facts))",
                "r = _to_decimal(_evaluate(expr.right, facts))",
                "return l > r",
            ],
        ),
        (
            "Ge",
            [
                "l = _to_decimal(_evaluate(expr.left, facts))",
                "r = _to_decimal(_evaluate(expr.right, facts))",
                "return l >= r",
            ],
        ),
        (
            "Add",
            [
                "l = _to_decimal(_evaluate(expr.left, facts))",
                "r = _to_decimal(_evaluate(expr.right, facts))",
                "return _ctx.add(l, r)",
            ],
        ),
        (
            "Sub",
            [
                "l = _to_decimal(_evaluate(expr.left, facts))",
                "r = _to_decimal(_evaluate(expr.right, facts))",
                "return _ctx.subtract(l, r)",
            ],
        ),
        (
            "Mul",
            [
                "l = _to_decimal(_evaluate(expr.left, facts))",
                "r = _to_decimal(_evaluate(expr.right, facts))",
                "return _ctx.multiply(l, r)",
            ],
        ),
        (
            "Div",
            [
                "l = _to_decimal(_evaluate(expr.left, facts))",
                "r = _to_decimal(_evaluate(expr.right, facts))",
                "return _ctx.divide(l, r)",
            ],
        ),
        (
            "In",
            [
                "item = str(_evaluate(expr.item, facts))",
                "coll = str(_evaluate(expr.collection, facts))",
                "return item in coll.split(',')",
            ],
        ),
        (
            "StringEq",
            [
                "l = str(_evaluate(expr.left, facts)).strip().casefold()",
                "r = str(_evaluate(expr.right, facts)).strip().casefold()",
                "return l == r",
            ],
        ),
        (
            "All",
            [
                "coll = _evaluate(expr.collection, facts)",
                "if not isinstance(coll, list):",
                "    return False",
                "return all(",
                "    _evaluate(expr.predicate,",
                "        {**facts, '_item_': (str(i), 'VERIFIED', ())})",
                "    for i in coll",
                ")",
            ],
        ),
        (
            "AnyExpr",
            [
                "coll = _evaluate(expr.collection, facts)",
                "if not isinstance(coll, list):",
                "    return False",
                "return any(",
                "    _evaluate(expr.predicate,",
                "        {**facts, '_item_': (str(i), 'VERIFIED', ())})",
                "    for i in coll",
                ")",
            ],
        ),
        (
            "CountExpr",
            [
                "coll = _evaluate(expr.collection, facts)",
                "if not isinstance(coll, list):",
                "    return 0",
                "return len(coll)",
            ],
        ),
    ]


def generate_evaluator(output_dir: Path) -> list[str]:
    """Generate the evaluator module into *output_dir*."""
    output_dir.mkdir(parents=True, exist_ok=True)
    lines: list[str] = [_GENERATED_HEADER]
    lines.append('"""Generated evaluator — independent oracle.')
    lines.append("")
    lines.append("Auto-generated from the DSL types; do not edit by hand.")
    lines.append('"""')
    lines.append("")
    lines.append("from __future__ import annotations")
    lines.append("")
    lines.append("from decimal import Decimal, getcontext as _get_ctx")
    lines.append("")
    lines.append("from kernel.rules.dsl.types import (")
    for name in _USED_TYPES:
        lines.append(f"    {name},")
    lines.append(")")
    lines.append("")
    lines.append("_ctx = _get_ctx()")
    lines.append("")
    lines.append("")
    lines.append("class _MissingFact(Exception):")
    lines.append("    pass")
    lines.append("")
    lines.append("")
    lines.append("class _ConflictedFact(Exception):")
    lines.append("    pass")
    lines.append("")
    lines.append("")
    lines.append("def _get_fact(facts, key):")
    lines.append("    entry = facts.get(key)")
    lines.append("    if entry is None:")
    lines.append("        raise _MissingFact(key)")
    lines.append("    value, status, citations = entry")
    lines.append("    if status == 'CONFLICTED':")
    lines.append("        raise _ConflictedFact(key)")
    lines.append("    if status != 'VERIFIED':")
    lines.append("        raise _MissingFact(key)")
    lines.append("    return value")
    lines.append("")
    lines.append("")
    lines.append("def _to_decimal(value):")
    lines.append("    if isinstance(value, Decimal):")
    lines.append("        return value")
    lines.append("    if isinstance(value, int):")
    lines.append("        return Decimal(value)")
    lines.append("    if isinstance(value, str):")
    lines.append("        return Decimal(value)")
    lines.append("    return Decimal(str(value))")
    lines.append("")
    lines.append("")
    lines.append("def _evaluate(expr, facts):")
    for cls, body in _dispatch_entries():
        lines.append(f"    if isinstance(expr, {cls}):")
        for bl in body:
            lines.append(f"        {bl}")
    lines.append("    raise ValueError(f'unhandled type: {type(expr).__name__}')")
    lines.append("")
    lines.append("")
    lines.append("def evaluate(condition, facts):")
    lines.append("    try:")
    lines.append("        return bool(_evaluate(condition, facts))")
    lines.append("    except _MissingFact:")
    lines.append("        return None")
    lines.append("    except _ConflictedFact:")
    lines.append("        raise")
    lines.append("")
    lines.append("")
    lines.append("__all__ = ['evaluate']")
    lines.append("")

    content = "\n".join(lines)
    target = output_dir / "evaluator.py"
    target.write_text(content, encoding="utf-8")
    return ["evaluator.py"]


def regenerate() -> int:
    """Regenerate all evaluator files. Returns 0 on success."""
    import subprocess  # nosec B404

    repo_root = Path(__file__).resolve().parents[2]
    output_dir = repo_root / "kernel" / "rules" / "_generated"
    generate_evaluator(output_dir)
    init_path = output_dir / "evaluator.py"
    # Format the generated file with ruff for consistency
    subprocess.run(  # nosec B603
        [".venv/bin/ruff", "format", str(init_path)],
        cwd=str(repo_root),
        capture_output=True,
    )
    return 0
